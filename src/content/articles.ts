/** Only what the client has cleared for publication. */
export const publishedArticles = articles.filter((a) => a.published);

export const articleBySlug = (slug: string) =>
  publishedArticles.find((a) => a.slug === slug);

/**
 * "مقالات قد تهمك" — same sector first, then anything else, so a sector with
 * only one published article still gets a full row instead of an empty block.
 */
export function relatedArticles(current: Article, limit = 3): Article[] {
  const others = publishedArticles.filter((a) => a.slug !== current.slug);
  const sameSector = others.filter((a) => a.sectorId === current.sectorId);
  const rest = others.filter((a) => a.sectorId !== current.sectorId);
  return [...sameSector, ...rest].slice(0, limit);
}
